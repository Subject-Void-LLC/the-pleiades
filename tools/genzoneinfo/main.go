// Command genzoneinfo generates internal/schedule/zoneinfo/zones.go: the
// list of IANA time zone names this build can actually load.
//
// The list is generated rather than hand-maintained, and generated from
// $GOROOT/lib/time/zoneinfo.zip specifically, because that is the exact
// archive the time/tzdata package embeds. Any other source -- the host's
// /usr/share/zoneinfo, a vendored copy, a list from the internet -- could
// name a zone this binary cannot load, which would turn a save-time
// allowlist check into a run-time failure inside the scheduler's scan loop.
//
// The standard library deliberately exposes no way to enumerate the zones
// it embeds; time.LoadLocation answers only about a name you already have.
// This closes that gap for the two callers that need a list: the /zoneinfo
// endpoint an operator picks a zone from, and the save-time validator.
//
// Run via `go generate ./internal/schedule/zoneinfo`. It takes no
// arguments: the output path is fixed.
package main

import (
	"archive/zip"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

// destFile is the one file this tool writes, relative to the directory the
// go:generate directive runs in (internal/schedule/zoneinfo).
const destFile = "zones.go"

func main() {
	log.SetFlags(0)

	zipPath, err := zoneinfoZip()
	if err != nil {
		log.Fatalf("genzoneinfo: locating zoneinfo.zip: %v", err)
	}
	names, err := readZoneNames(zipPath)
	if err != nil {
		log.Fatalf("genzoneinfo: reading %s: %v", zipPath, err)
	}
	if len(names) == 0 {
		log.Fatalf("genzoneinfo: %s contained no zones", zipPath)
	}

	out, err := renderFile(names)
	if err != nil {
		log.Fatalf("genzoneinfo: %v", err)
	}
	// The destination is fixed rather than taken from argv. There is
	// exactly one file this tool writes, and accepting a path would mean a
	// build tool that writes wherever it is pointed -- which is both a
	// gosec taint finding and a real way to overwrite the wrong file from
	// a mistyped go:generate line.
	if err := os.WriteFile(destFile, out, 0o600); err != nil {
		log.Fatalf("genzoneinfo: writing %s: %v", destFile, err)
	}
	fmt.Printf("genzoneinfo: wrote %d zones to %s\n", len(names), destFile)
}

// zoneinfoZip returns the path to the Go toolchain's own embedded tzdata
// archive.
func zoneinfoZip() (string, error) {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return "", err
	}
	path := filepath.Join(strings.TrimSpace(string(out)), "lib", "time", "zoneinfo.zip")
	if _, err := os.Stat(path); err != nil {
		return "", err
	}
	return path, nil
}

// readZoneNames returns every loadable zone name in the archive, sorted.
//
// Entries that are not zones (the archive's own metadata files, and the
// legacy single-letter military zones under a directory of their own) are
// filtered by the only test that actually matters: whether time.LoadLocation
// accepts the name. That makes the filter a property of the runtime rather
// than a list of exceptions this tool would have to keep current.
func readZoneNames(path string) ([]string, error) {
	r, err := zip.OpenReader(path)
	if err != nil {
		return nil, err
	}
	defer func() { _ = r.Close() }()

	var names []string
	for _, f := range r.File {
		if f.FileInfo().IsDir() {
			continue
		}
		name := f.Name
		// Files with no slash are either the archive's metadata or the
		// three-letter legacy aliases; the zones an operator picks from
		// are Area/Location, plus UTC itself.
		if !strings.Contains(name, "/") && name != "UTC" {
			continue
		}
		if _, err := time.LoadLocation(name); err != nil {
			continue
		}
		names = append(names, name)
	}
	sort.Strings(names)
	return names, nil
}

// renderFile emits the generated Go source.
func renderFile(names []string) ([]byte, error) {
	var b strings.Builder
	b.WriteString(`// Code generated by tools/genzoneinfo. DO NOT EDIT.

package zoneinfo

// names is every IANA time zone this build can load, taken from the same
// archive time/tzdata embeds. See tools/genzoneinfo for why it is generated
// from there rather than from the host system.
var names = []string{
`)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	return []byte(b.String()), nil
}
