// filterStage names one cel.EnvOption engine.CELLibraryOptions() returns,
// in the exact order that function returns them, so generateFilters can
// attribute each newly discovered function or macro to a human-readable
// section. This is presentation grouping only: the functions, signatures
// and examples rendered under each stage all come from the live
// engine.CELVariableOptions/CELLibraryOptions, never hand-typed here. If
// engine.CELLibraryOptions ever reorders or adds an entry without a
// matching update to filterStageLabels below, generateFilters's own
// length check fails the build rather than silently mislabeling a
// section.
type filterStage struct {
	title string
	intro string
}

// generateFilters emits outDir/filters/index.md: every function and macro
// callable from a when/when_or/when_cel expression beyond CEL's own
// built-in operators, whether pkg/filters registers it or a cel-go
// standard extension does. Nothing here is a second, hand-maintained copy
// of a function's name or signature: this builds the exact baseline
// environment engine.NewCELEvaluator would build with no libraries, then
// extends it one engine.CELLibraryOptions() entry at a time, diffing
// cel.Env.Functions() and cel.Env.Macros() after each step by overload ID
// (not by function name: ext.Network adds new overloads to the
// standard library's own pre-existing "string" conversion function, which
// a name-level diff would miss entirely) to discover exactly what each
// step adds. A page produced this way cannot claim a function exists, or
// a signature reads a certain way, that the real, shipped engine
// disagrees with.
func generateFilters(outDir string) error {
	filtersDir := filepath.Join(outDir, "filters")
	if err := os.MkdirAll(filtersDir, 0o755); err != nil { // #nosec G301 -- generated docs, not secret material
		return fmt.Errorf("creating %s: %w", filtersDir, err)
	}

	libs, err := engine.ConditionLibraries()
	if err != nil {
		return fmt.Errorf("gendocs: %w", err)
	}
	stages := filterStageLabels()
	if len(stages) != len(libs) {
		return fmt.Errorf("gendocs: filterStageLabels() has %d entries but engine.CELLibraryOptions() returns %d; "+
			"update tools/gendocs/filters.go's stage table to match", len(stages), len(libs))
	}

	var b strings.Builder
	b.WriteString(frontMatter("beta"))
	b.WriteString("# Filter reference\n\n")
	b.WriteString("Every function and macro callable from a `when`, `when_or` or `when_cel` expression, " +
		"beyond CEL's own built-in operators (`==`, `&&`, `in`, and so on; see the " +
		"[CEL language definition](https://github.com/google/cel-spec/blob/master/doc/langdef.md) for " +
		"those). A filter is not a Collection method: it is a pure, deterministic function of its " +
		"arguments, with no device, no capability and no execution context. " +
		"This page is generated by diffing the real CEL environment `engine.NewCELEvaluator` builds " +
		"against a bare baseline with no libraries added, so a function or signature listed here is " +
		"proven callable, not merely intended.\n\n")
	b.WriteString("A signature written `filters.safeInt(dyn, int) -> int` means the first argument accepts " +
		"any CEL type (converted to a string before parsing); a signature's own fallback argument, where " +
		"one exists, keeps its exact declared type, so a value the wrong literal type there fails to " +
		"compile rather than being silently coerced.\n\n")

	for i, lib := range libs {
		if len(lib.Functions) == 0 {
			continue
		}
		fmt.Fprintf(&b, "## %s\n\n", stages[i].title)
		b.WriteString(stages[i].intro + "\n\n")
		for _, fd := range lib.Functions {
			if fd.Macro {
				renderMacroDoc(&b, fd)
			} else {
				renderFunctionDoc(&b, fd)
			}
		}
	}

	return os.WriteFile(filepath.Join(filtersDir, "index.md"), []byte(b.String()), 0o644) // #nosec G306 -- generated docs, not secret material
}

// filterStageLabels is the presentation-only label table paired
// positionally against engine.CELLibraryOptions()'s own returned slice
// (ext.Network(), ext.Encoders(), cel.OptionalTypes(), filtersLib(), in
// that order). Only the title and intro sentence are hand-written; every
// function name, signature and example rendered under a stage comes from
// the live env diff in generateFilters.
func filterStageLabels() []filterStage {
	return []filterStage{
		{
			title: "Network & addressing (`ext.Network`)",
			intro: "cel-go's own `ext.Network()`, built on Go's `net/netip`. `ip` and `net.CIDR` values are " +
				"opaque types with a custom type adapter; a `net/netip.Addr` or `netip.Prefix` from Go code " +
				"converts into this environment directly. Parsing is strict: an IPv4-mapped IPv6 address or " +
				"a zone suffix is rejected, not silently accepted.",
		},
		{
			title: "Encoding (`ext.Encoders`)",
			intro: "cel-go's own `ext.Encoders()`. `base64.encode` takes `bytes` and returns `string`; " +
				"`base64.decode` takes `string` and returns `bytes`, the reverse of what the names alone " +
				"suggest. Reach for `base64.encode(bytes(x))` and `string(base64.decode(x))` when the value " +
				"in hand is a CEL string rather than bytes.",
		},
		{
			title: "Optional values (`cel.OptionalTypes`)",
			intro: "cel-go's own `cel.OptionalTypes()`. This is the environment's answer to Ansible's " +
				"`default` filter: `stat.?retries.orValue(0)` reads as \"the value at `retries` if present, " +
				"otherwise `0`\", and covers a field that may be **absent** entirely. It is a different " +
				"problem from a field that is **present but malformed**, which the `filters.safe*` family " +
				"above answers instead; the two are not interchangeable.",
		},
		{
			title: "First-party filters (`filters.*`)",
			intro: "`pkg/filters`, registered under the flat `filters.` prefix, a namespace independent " +
				"of a Collection's `<namespace>.<method>` FQCN (the two never cross-reference each other, " +
				"so no collision is possible even in principle). Every function here is independently " +
				"unit-tested as plain Go, with no dependency on CEL; `internal/engine/cel_filters.go` is " +
				"the only translation between the two.",
		},
	}
}

func renderFunctionDoc(b *strings.Builder, fd engine.ConditionFunction) {
	fmt.Fprintf(b, "### `%s`\n\n", fd.Name)
	if fd.Description != "" {
		fmt.Fprintf(b, "%s\n\n", fd.Description)
	}
	for _, od := range fd.Overloads {
		fmt.Fprintf(b, "- `%s`\n", od.Signature)
		for _, ex := range od.Examples {
			for _, line := range strings.Split(ex, "\n") {
				fmt.Fprintf(b, "  - `%s`\n", line)
			}
		}
	}
	b.WriteString("\n")
}

func renderMacroDoc(b *strings.Builder, md engine.ConditionFunction) {
	fmt.Fprintf(b, "### `%s` (macro)\n\n", md.Name)
	if md.Description != "" {
		fmt.Fprintf(b, "%s\n\n", md.Description)
	}
	for _, ex := range md.Overloads[0].Examples {
		for _, line := range strings.Split(ex, "\n") {
			fmt.Fprintf(b, "- `%s`\n", line)
		}
	}
	b.WriteString("\n")
}
