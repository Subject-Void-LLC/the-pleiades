// Package main: tests for the rules about generated code.
package main

import (
	"strings"
	"testing"
)

// entry builds a staged entry for a table row.
func entry(path string, kind changeKind, content string) stagedEntry {
	return stagedEntry{stagedFile: stagedFile{Path: path, Kind: kind}, Content: []byte(content)}
}

// generatedEntContent is what ent writes at the top of its output, which
// is the only thing that marks a file under internal/ent as generated.
const generatedEntContent = "// Code generated by ent, DO NOT EDIT.\n\npackage ent\n"

func TestCheckEntRegeneratedRefusesASchemaEditAlone(t *testing.T) {
	entries := []stagedEntry{
		entry("internal/ent/schema/journal.go", changeModified, "package schema\n"),
	}
	if !hasRule(checkGenerated(entries), SeverityFail, "regenerated code") {
		t.Error("accepted a schema edit with no regenerated code beside it")
	}
}

func TestCheckEntRegeneratedAcceptsASchemaEditWithItsOutput(t *testing.T) {
	entries := []stagedEntry{
		entry("internal/ent/schema/journal.go", changeModified, "package schema\n"),
		entry("internal/ent/journalentry.go", changeModified, generatedEntContent),
	}
	if hasRule(checkGenerated(entries), SeverityFail, "regenerated code") {
		t.Error("refused a schema edit that staged its regenerated code")
	}
}

func TestCheckEntRegeneratedDoesNotCountAHandWrittenFile(t *testing.T) {
	// internal/ent holds four hand-written files. Staging one of them is
	// not evidence that anything was regenerated, and a path-based rule
	// would have counted it.
	for _, path := range []string{
		"internal/ent/generate.go",
		"internal/ent/migrate/apply.go",
		"internal/ent/migrate/parity_test.go",
		"internal/ent/migrate/gen/main.go",
	} {
		t.Run(path, func(t *testing.T) {
			entries := []stagedEntry{
				entry("internal/ent/schema/journal.go", changeModified, "package schema\n"),
				entry(path, changeModified, "package x\n"),
			}
			if !hasRule(checkGenerated(entries), SeverityFail, "regenerated code") {
				t.Errorf("counted the hand-written %s as regenerated output", path)
			}
		})
	}
}

func TestCheckEntMigrationsRefusesANewEntityMissingADialect(t *testing.T) {
	cases := map[string][]stagedEntry{
		"neither dialect": {
			entry("internal/ent/schema/journal.go", changeAdded, "package schema\n"),
			entry("internal/ent/journalentry.go", changeAdded, generatedEntContent),
		},
		"sqlite only": {
			entry("internal/ent/schema/journal.go", changeAdded, "package schema\n"),
			entry("internal/ent/journalentry.go", changeAdded, generatedEntContent),
			entry("internal/ent/migrate/migrations/sqlite/0021_add_journal.sql", changeAdded, "create table x;\n"),
		},
		"postgres only": {
			entry("internal/ent/schema/journal.go", changeAdded, "package schema\n"),
			entry("internal/ent/journalentry.go", changeAdded, generatedEntContent),
			entry("internal/ent/migrate/migrations/postgres/0018_add_journal.sql", changeAdded, "create table x;\n"),
		},
	}
	for name, entries := range cases {
		t.Run(name, func(t *testing.T) {
			if !hasRule(checkGenerated(entries), SeverityFail, "both dialects") {
				t.Error("accepted a new entity with an incomplete migration set")
			}
		})
	}
}

func TestCheckEntMigrationsAcceptsBothDialects(t *testing.T) {
	entries := []stagedEntry{
		entry("internal/ent/schema/journal.go", changeAdded, "package schema\n"),
		entry("internal/ent/journalentry.go", changeAdded, generatedEntContent),
		entry("internal/ent/migrate/migrations/sqlite/0021_add_journal.sql", changeAdded, "create table x;\n"),
		entry("internal/ent/migrate/migrations/postgres/0018_add_journal.sql", changeAdded, "create table x;\n"),
	}
	if hasRule(checkGenerated(entries), SeverityFail, "both dialects") {
		t.Error("refused a new entity that staged a migration for both dialects")
	}
}

func TestCheckEntMigrationsIgnoresAnEditToAnExistingSchema(t *testing.T) {
	// The rule fires on an added schema file only. It cannot tell a field
	// addition from a comment fix, and parity_test.go catches the rest.
	entries := []stagedEntry{
		entry("internal/ent/schema/journal.go", changeModified, "package schema\n"),
		entry("internal/ent/journalentry.go", changeModified, generatedEntContent),
	}
	if hasRule(checkGenerated(entries), SeverityFail, "both dialects") {
		t.Error("demanded migrations for an edit to an existing schema")
	}
}

func TestCheckCatalogRegeneratedOnlyWarns(t *testing.T) {
	// forge runs with --skip-existing and is genuinely idempotent, so an
	// edit that produces no new file is legitimate.
	entries := []stagedEntry{
		entry("internal/forge/catalogdata/methods.go", changeModified, "package catalogdata\n"),
	}
	findings := checkGenerated(entries)
	if !hasRule(findings, SeverityWarn, "catalog data") {
		t.Error("said nothing about a catalog data edit with no regenerated entry")
	}
	if hasRule(findings, SeverityFail, "catalog data") {
		t.Error("refused a commit for something that can legitimately be a no-op")
	}
}

func TestCheckGeneratedIsSilentOnAnOrdinaryCommit(t *testing.T) {
	entries := []stagedEntry{
		entry("internal/journal/store.go", changeAdded, "package journal\n"),
		entry("README.md", changeModified, "# x\n"),
	}
	if findings := checkGenerated(entries); len(findings) != 0 {
		t.Errorf("reported %d findings against a commit touching no generated tree: %+v", len(findings), findings)
	}
}

// schemaBefore is a schema file as its parent commit held it.
const schemaBefore = `package schema

// Fact is a fact.
type Fact struct{}

// Fields of the Fact.
func (Fact) Fields() []ent.Field {
	return []ent.Field{
		field.String("key"), // the key
	}
}
`

// modifiedSchema is a modified schema entry with its before and after.
func modifiedSchema(before, after string) stagedEntry {
	e := entry("internal/ent/schema/fact.go", changeModified, after)
	e.Before = []byte(before)
	return e
}

func TestCheckEntRegeneratedAcceptsACommentOnlySchemaEdit(t *testing.T) {
	after := strings.Replace(schemaBefore, "// Fact is a fact.", "// Fact is a fact, now said\n// at greater length.", 1)
	after = strings.Replace(after, "// the key", "// the key, which names the history", 1)
	if hasRule(checkGenerated([]stagedEntry{modifiedSchema(schemaBefore, after)}), SeverityFail, "regenerated code") {
		t.Error("refused a schema edit that changed only comments, which go generate writes nothing for")
	}
}

func TestCheckEntRegeneratedStillRefusesACodeChangeBesideComments(t *testing.T) {
	for name, after := range map[string]string{
		"a field added":              strings.Replace(schemaBefore, `field.String("key"), // the key`, "field.String(\"key\"), // the key\n\t\tfield.Int(\"seq\"),", 1),
		"a field modified":           strings.Replace(schemaBefore, `field.String("key")`, `field.String("key").Immutable()`, 1),
		"code that no longer parses": strings.Replace(schemaBefore, "return", "retrun", 1),
	} {
		t.Run(name, func(t *testing.T) {
			if !hasRule(checkGenerated([]stagedEntry{modifiedSchema(schemaBefore, after)}), SeverityFail, "regenerated code") {
				t.Errorf("accepted %s with no regenerated code", name)
			}
		})
	}
	// With no parent content to compare (a rename), the edit counts as real.
	e := entry("internal/ent/schema/fact.go", changeModified, schemaBefore)
	if !hasRule(checkGenerated([]stagedEntry{e}), SeverityFail, "regenerated code") {
		t.Error("accepted a schema edit whose parent content was not read")
	}
	// One comment-only file does not excuse a real edit beside it.
	other := modifiedSchema(schemaBefore, strings.Replace(schemaBefore, `field.String("key")`, `field.Int("key")`, 1))
	other.Path = "internal/ent/schema/journal.go"
	if !hasRule(checkGenerated([]stagedEntry{modifiedSchema(schemaBefore, schemaBefore+"// trailing note\n"), other}), SeverityFail, "regenerated code") {
		t.Error("a comment-only file excused a real schema change beside it")
	}
}

func TestCommentsOnlyCountsWhatItCannotCompareAsAChange(t *testing.T) {
	if commentsOnly(modifiedSchema("package schema\nfunc (", schemaBefore)) {
		t.Error("a parent that does not parse read as comment-only")
	}
	added := modifiedSchema(schemaBefore, schemaBefore)
	added.Kind = changeAdded
	if commentsOnly(added) {
		t.Error("an added file read as comment-only")
	}
	if !commentsOnly(modifiedSchema(schemaBefore, schemaBefore)) {
		t.Error("an unchanged file did not read as comment-only")
	}
}

func TestCheckBackupListingWarnsOnANewEntityAlone(t *testing.T) {
	added := []stagedEntry{entry("internal/ent/schema/fact_coverage.go", changeAdded, "package schema\n")}
	if !hasRule(checkGenerated(added), SeverityWarn, "new table in every backup") {
		t.Error("said nothing about a new entity with no recaptured backup listing")
	}
	with := append(added, entry("internal/backup/testdata/toc_migrated.txt", changeModified, ";\n"))
	if hasRule(checkGenerated(with), SeverityWarn, "new table in every backup") {
		t.Error("warned although the listing was recaptured in the same commit")
	}
	modified := []stagedEntry{modifiedSchema(schemaBefore, schemaBefore+"// note\n")}
	if hasRule(checkGenerated(modified), SeverityWarn, "new table in every backup") {
		t.Error("warned on a schema file that adds no entity")
	}
	for _, f := range checkGenerated(added) {
		if f.Severity == SeverityFail && strings.Contains(f.Rule, "backup") {
			t.Error("the backup listing rule blocked a commit; it only warns")
		}
	}
}
