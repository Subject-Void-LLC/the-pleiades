// Package externalscaffold: the template for a script program's method file
// (forge new-external --script).
package externalscaffold

// scriptMethodTemplateSource is the method file of a program that wraps a
// script: the script embedded with go:embed, the descriptor, and the body
// that writes the script into the run's private temporary directory and runs
// it there with the interpreter named when the program was generated.
//
// What the body hands the script, and what it takes back, is the whole
// contract, and both halves are narrow on purpose. In: the task's params as
// one JSON document on stdin, an environment rebuilt from four variables,
// and the script's own path as its one argument. Never a credential: the
// RunbookContext the program is handed may hold one, and the body reads it
// only to mask it out of the script's stderr. Out: exactly one JSON object
// on stdout, holding changed and, optionally, facts and stats. Anything else
// fails the task, so a script that printed nothing, or a stray line beside
// its answer, is never read as success.
const scriptMethodTemplateSource = `// This file implements one Collection method, {{quote .Name}}, a wrapper
// around the script in {{.ScriptFile}}. Generated by pleiades forge
// new-external --script.
//
// The script is embedded in this program with go:embed, so the digest an
// operator approves covers it: a changed script is a new build to approve.
// The interpreter that runs it, {{.Interpreter}}, is not embedded and is
// outside that digest: whatever is at that path on the machine running The
// Pleiades runs the script.
//
// Each run writes the script into the run's private temporary directory,
// which the loader's confinement lets this program write, and runs it there
// with the task's params as one JSON document on stdin. The script answers
// by printing exactly one JSON object on stdout:
//
//	{"changed": true, "stats": {"lines": 3}, "facts": {"seen": "yes"}}
//
// changed is required and must be true or false. stats and facts are
// optional objects, and every key in either becomes a value the task's
// register reads. Anything else on stdout fails the task, and so does a
// non-zero exit, whose stderr is reported, cut short and masked. The method
// acts on no device, so no fact reaches a device's fact store.
//
// The script is never handed a credential, on stdin, in its arguments or in
// its environment.

package main

import (
	"bytes"
	"context"
	_ "embed"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/Subject-Void-LLC/the-pleiades/pkg/collection"
	"github.com/Subject-Void-LLC/the-pleiades/pkg/inventory"
	"github.com/Subject-Void-LLC/the-pleiades/pkg/sdk"
)

// {{.Prefix}}FQCN is this method's fully-qualified name. It is the name a
// runbook task uses, and it prefixes every error the method returns.
const {{.Prefix}}FQCN = {{quote .Name}}

// {{.Prefix}}Interpreter is the program that runs the script, by its
// absolute path. It is outside the approved digest.
const {{.Prefix}}Interpreter = {{quote .Interpreter}}

// {{.Prefix}}ScriptName is the script's file name, in this directory and in
// the run's private temporary directory.
const {{.Prefix}}ScriptName = {{quote .ScriptFile}}

// {{.Prefix}}Script is the script itself, compiled into this program.
//
//go:embed {{.ScriptFile}}
var {{.Prefix}}Script []byte

// The bounds on one run of the script.
const (
	// {{.Prefix}}MaxStdout is the most the script may print on stdout. Its
	// answer is one small JSON object; a script printing more fails.
	{{.Prefix}}MaxStdout = 1 << 20

	// {{.Prefix}}MaxStderr is how much of the script's stderr a failure
	// reports. The rest is read and dropped.
	{{.Prefix}}MaxStderr = 4 << 10

	// {{.Prefix}}WaitDelay is how long the method waits, once the script
	// has exited or been stopped, for anything it started that still holds
	// its output open.
	{{.Prefix}}WaitDelay = 5 * time.Second
)

// {{.Prefix}}Reserved are the stat keys The Pleiades gives a meaning of its
// own (an undo, a prediction, warnings, a diff). A script setting one would
// claim something this wrapper never checked, so the task fails instead.
var {{.Prefix}}Reserved = map[string]bool{
	sdk.StatInverse:        true,
	sdk.StatPredicted:      true,
	sdk.StatPredictedPaths: true,
	sdk.StatWarnings:       true,
	sdk.StatDiff:           true,
	sdk.StatFactKeys:       true,
}

// {{.FunctionName}}Descriptor returns the registry entry for this method.
// main hands it to external.MainProgram, which validates it with
// collection.Register before answering anything, exactly as a built-in
// method is validated.
func {{.FunctionName}}Descriptor() collection.Descriptor {
	return collection.Descriptor{
		Name: {{.Prefix}}FQCN,
		Manifest: collection.Manifest{
			// The script runs beside The Pleiades and acts on no device, so a
			// task calling it needs no hosts: and is handed no credential.
			ExecutionContext: collection.ExecutionContext{Site: collection.SiteController, Device: collection.DeviceNone},
{{- if .EngineConstraint}}
			// The oldest Pleiades this program runs on: the release that
			// generated it.
			EngineVersion: {{quote .EngineConstraint}},
{{- end}}
			Status: collection.StatusImplemented,
			Reversibility: collection.Reversibility{
				Reversible: false,
				Notes:      "A script's effect is whatever its code does, which this wrapper cannot see, so no run records an undo. Undo it with a task of its own.",
			},
			SupportsCheck: false,
			NoCheckReason: "A check must change nothing, and this wrapper cannot tell a script that only reads from one that writes, so the only way to learn what the script would do is to run it.",
			Doc:           {{.Prefix}}Doc(),
		},
		Invoke: {{.FunctionName}},
	}
}

// {{.Prefix}}Doc is this method's reference documentation, the text
// pleiades doc prints for it. Rewrite it to say what the script does.
func {{.Prefix}}Doc() collection.Doc {
	return collection.Doc{
		Summary:     "Runs the script embedded in this program, " + {{.Prefix}}ScriptName + ", with " + {{.Prefix}}Interpreter + ".",
		Description: "Runs the embedded script beside The Pleiades with the task's params as one JSON document on stdin, and reports what it prints: one JSON object holding changed and, optionally, stats and facts. It acts on no device and is handed no credential.",
		// Declare every parameter the script reads here, with its type:
		// pleiades validate refuses a task passing one that is not declared,
		// since the script would otherwise be handed a misspelled key and
		// run as though it had never been written.
		Params: nil,
		Examples: []collection.Example{
			{Name: "Run the script", RunbookYAML: "- name: Run the script\n  " + {{.Prefix}}FQCN + ":\n  register: result\n"},
		},
	}
}

// {{.FunctionName}} is the method's body. It writes the embedded script
// into a directory of its own inside the run's private temporary directory,
// runs it there with the task's params on stdin, and reads back its answer.
// The device argument is unused: the method acts on none.
func {{.FunctionName}}(ctx context.Context, rc sdk.RunbookContext, _ inventory.InventoryItem, params map[string]any) (collection.Result, error) {
	if params == nil {
		params = map[string]any{}
	}
	input, err := json.Marshal(params)
	if err != nil {
		return collection.Result{}, fmt.Errorf("%s: encoding the params: %w", {{.Prefix}}FQCN, err)
	}

	// os.MkdirTemp reads TMPDIR, which the loader sets to the run's
	// private scratch directory: the one place a confined program may write.
	dir, err := os.MkdirTemp("", "script-")
	if err != nil {
		return collection.Result{}, fmt.Errorf("%s: %w", {{.Prefix}}FQCN, err)
	}
	defer func() { _ = os.RemoveAll(dir) }()
	script := filepath.Join(dir, {{.Prefix}}ScriptName)
	if err := os.WriteFile(script, {{.Prefix}}Script, 0o600); err != nil {
		return collection.Result{}, fmt.Errorf("%s: writing the script: %w", {{.Prefix}}FQCN, err)
	}

	stdout := &{{.Prefix}}Capped{limit: {{.Prefix}}MaxStdout}
	stderr := &{{.Prefix}}Capped{limit: {{.Prefix}}MaxStderr}
	cmd := exec.CommandContext(ctx, {{.Prefix}}Interpreter, script) // #nosec G204 -- the interpreter fixed when this program was generated, and the embedded script
	cmd.Dir = dir
	cmd.Env = {{.Prefix}}Environment(dir)
	cmd.Stdin = bytes.NewReader(input)
	cmd.Stdout, cmd.Stderr = stdout, stderr
	cmd.WaitDelay = {{.Prefix}}WaitDelay

	if err := cmd.Run(); err != nil {
		said := {{.Prefix}}Masked(strings.TrimSpace(stderr.buf.String()), rc.InjectSecrets())
		if stderr.over {
			said += " [stderr cut short]"
		}
		var exit *exec.ExitError
		switch {
		case ctx.Err() != nil:
			return collection.Result{}, fmt.Errorf("%s: the script was stopped: %w; stderr: %s", {{.Prefix}}FQCN, ctx.Err(), said)
		case errors.As(err, &exit):
			return collection.Result{}, fmt.Errorf("%s: the script exited %d; stderr: %s", {{.Prefix}}FQCN, exit.ExitCode(), said)
		default:
			return collection.Result{}, fmt.Errorf("%s: running %s: %w", {{.Prefix}}FQCN, {{.Prefix}}Interpreter, err)
		}
	}
	if stdout.over {
		return collection.Result{}, fmt.Errorf("%s: the script printed more than %d bytes on stdout, where it must print one JSON object", {{.Prefix}}FQCN, {{.Prefix}}MaxStdout)
	}
	return {{.Prefix}}Answer(rc, stdout.buf.Bytes())
}

// {{.Prefix}}Environment is the script's whole environment: HOME and TMPDIR
// set to its own directory, and PATH, LANG, LC_ALL and TZ as this program
// was given them, when it was. Nothing else this program holds is passed on.
func {{.Prefix}}Environment(dir string) []string {
	env := []string{"HOME=" + dir, "TMPDIR=" + dir}
	for _, key := range []string{"PATH", "LANG", "LC_ALL", "TZ"} {
		if v, ok := os.LookupEnv(key); ok {
			env = append(env, key+"="+v)
		}
	}
	return env
}

// {{.Prefix}}Answer reads the script's stdout: exactly one JSON object
// holding changed, true or false, and optionally stats and facts, each an
// object. It records every key of both as a stat and returns changed.
// Anything else is a failure, an empty stdout included.
func {{.Prefix}}Answer(rc sdk.RunbookContext, out []byte) (collection.Result, error) {
	fail := func(format string, args ...any) (collection.Result, error) {
		return collection.Result{}, fmt.Errorf("%s: the script's answer: "+format, append([]any{ {{.Prefix}}FQCN}, args...)...)
	}
	trimmed := bytes.TrimSpace(out)
	if len(trimmed) == 0 {
		return fail("it printed nothing on stdout, where it must print one JSON object holding changed")
	}
	if trimmed[0] != '{' {
		return fail("stdout must be one JSON object, and it starts with %q", string(trimmed[:min(len(trimmed), 40)]))
	}
	dec := json.NewDecoder(bytes.NewReader(trimmed))
	var fields map[string]json.RawMessage
	if err := dec.Decode(&fields); err != nil {
		return fail("stdout is not a JSON object: %v", err)
	}
	if rest := bytes.TrimSpace(trimmed[dec.InputOffset():]); len(rest) != 0 {
		return fail("stdout holds more than one JSON object")
	}

	var changed bool
	values := map[string]any{}
	for _, field := range {{.Prefix}}SortedKeys(fields) {
		raw := fields[field]
		switch field {
		case "changed":
			if bytes.Equal(bytes.TrimSpace(raw), []byte("null")) || json.Unmarshal(raw, &changed) != nil {
				return fail("changed must be true or false, and it is %s", raw)
			}
		case "stats", "facts":
			object, err := {{.Prefix}}Object(raw)
			if err != nil {
				return fail("%s must be a JSON object: %v", field, err)
			}
			for key, v := range object {
				if {{.Prefix}}Reserved[key] {
					return fail("%q is a key The Pleiades reserves", key)
				}
				if _, twice := values[key]; twice {
					return fail("%q is set twice", key)
				}
				values[key] = v
			}
		default:
			return fail("%q is not one of changed, stats or facts", field)
		}
	}
	if _, ok := fields["changed"]; !ok {
		return fail("it holds no changed, which must say whether the script changed anything")
	}
	for _, key := range {{.Prefix}}SortedKeys(values) {
		if err := rc.SetStat(key, values[key]); err != nil {
			return collection.Result{}, fmt.Errorf("%s: %w", {{.Prefix}}FQCN, err)
		}
	}
	return collection.Result{Changed: changed}, nil
}

// {{.Prefix}}Object decodes raw as a JSON object, a whole number in it as an
// int64 and any other number as a float64.
func {{.Prefix}}Object(raw json.RawMessage) (map[string]any, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	var object map[string]any
	if err := dec.Decode(&object); err != nil {
		return nil, err
	}
	if object == nil {
		return nil, errors.New("it is null")
	}
	return {{.Prefix}}Numbers(object).(map[string]any), nil
}

// {{.Prefix}}Numbers replaces every json.Number in v with an int64 when it
// is whole and a float64 otherwise.
func {{.Prefix}}Numbers(v any) any {
	switch t := v.(type) {
	case json.Number:
		if i, err := t.Int64(); err == nil {
			return i
		}
		f, _ := t.Float64()
		return f
	case map[string]any:
		for k, e := range t {
			t[k] = {{.Prefix}}Numbers(e)
		}
		return t
	case []any:
		for i, e := range t {
			t[i] = {{.Prefix}}Numbers(e)
		}
		return t
	default:
		return v
	}
}

// {{.Prefix}}SortedKeys returns m's keys in order, so an answer is read the
// same way every time.
func {{.Prefix}}SortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// {{.Prefix}}Masked replaces every value of secrets in s, longest first, so a
// secret this program holds never travels in an error. The script is never
// handed one, so this guards against one reaching it some other way.
func {{.Prefix}}Masked(s string, secrets map[string]string) string {
	values := make([]string, 0, len(secrets))
	for _, v := range secrets {
		if v != "" {
			values = append(values, v)
		}
	}
	sort.Slice(values, func(i, j int) bool { return len(values[i]) > len(values[j]) })
	for _, v := range values {
		s = strings.ReplaceAll(s, v, "********")
	}
	return s
}

// {{.Prefix}}Capped keeps the first limit bytes written to it and records
// whether more came. It never refuses a write, so a script printing too much
// is not stalled on a full pipe: the rest is read and dropped.
type {{.Prefix}}Capped struct {
	buf   bytes.Buffer
	limit int
	over  bool
}

// Write implements io.Writer.
func (c *{{.Prefix}}Capped) Write(p []byte) (int, error) {
	if room := c.limit - c.buf.Len(); room < len(p) {
		if room > 0 {
			c.buf.Write(p[:room])
		}
		c.over = true
		return len(p), nil
	}
	c.buf.Write(p)
	return len(p), nil
}
`
