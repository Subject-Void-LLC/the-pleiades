package pluginscaffold

// pluginTemplateSource is the sync plugin source file template: a
// syncplugin registration in init(), and a four-method skeleton whose
// methods return an explicit not-implemented error rather than a plausible
// zero value.
//
// The "declared is not implemented" guardrail is the same one
// collectionscaffold applies to Collection stubs, and it matters more here,
// not less. A Collection stub that silently succeeded would fail a task; a
// Sync that silently succeeded would report a clean reconciliation of zero
// devices, which looks exactly like an upstream system that happens to be
// empty.
const pluginTemplateSource = `// Package {{.PackageName}} implements the "{{.Name}}" inventory sync plugin.
// Generated by pleiades forge new-plugin (internal/forge/pluginscaffold).
//
// This package's init registers "{{.Name}}" into the shared syncplugin
// registry with Status declared, meaning the shape below is real,
// buildable, testable Go code that does not yet talk to anything. Every
// method returns an explicit error saying so. Nothing here may flip to
// StatusImplemented on the strength of a test that fakes the upstream
// system: PLAN.md Section 6a's plugins exist to read a real external source
// of truth, and a plugin proven only against a fake has proven only that
// the fake works.
//
// What a human fills in, in order:
//
//  1. Connect: resolve the credential named by cfg.CredentialName through
//     internal/credential, authenticate, and keep whatever session or token
//     the upstream system hands back. Never read a secret from the
//     environment; Section 6c is explicit that discovery credentials are
//     looked up, not inlined.
//  2. Discover: page the upstream API, yielding one record.Record per
//     device through a RecordIterator. Page rather than materialize, so
//     memory stays flat regardless of fleet size.
//  3. Classify: derive a Section 6d classification path from the raw
//     upstream fields and resolve it with syncplugin.ClassifyPath. Do not
//     switch on vendor strings here; the rule tree is where classification
//     is decided, and a plugin's job is only to say which path a record
//     maps to.
//  4. Sync: delegate to syncplugin.Reconcile. Do not hand-roll the
//     add/update/conflict decision, or this plugin's reconciliation report
//     will quietly stop meaning the same thing as every other plugin's.
//
// Because this package lives under internal/, it is reachable only from
// code inside this module or a fork of it. Registration also only happens
// if something imports it: add a blank import to
// internal/inventory/plugins/builtins.go, or this plugin will pass its own
// tests while being invisible to the real binary (FAILURE_PATTERNS.md #52).
package {{.PackageName}}

import (
	"context"
	"fmt"

	inv "github.com/Subject-Void-LLC/the-pleiades/internal/inventory"
	"github.com/Subject-Void-LLC/the-pleiades/internal/inventory/record"
	"github.com/Subject-Void-LLC/the-pleiades/internal/inventory/syncplugin"
)

// Name is this plugin's registration key and the value stamped into the
// SourceAuthority of every device it syncs.
const Name = {{quote .Name}}

// errNotImplemented is the single refusal every method below returns. It
// names the plugin so an operator running several sees which one is still a
// skeleton.
var errNotImplemented = fmt.Errorf("sync plugin %q is declared but not implemented", Name)

func init() {
	syncplugin.MustRegister(syncplugin.Descriptor{
		Name:        Name,
		Description: {{quote .Description}},
		DefaultConfig: syncplugin.Config{
			Name:     Name,
			Endpoint: {{quote .Endpoint}},
			ReadOnly: {{.ReadOnly}},
		},
		Status: syncplugin.StatusDeclared,
		New:    func() syncplugin.Plugin { return New() },
	})
}

// {{.TypeName}} is the "{{.Name}}" sync plugin. The zero value is not
// usable; construct one with New.
type {{.TypeName}} struct {
	// cfg is retained by Connect so the later methods can read the endpoint,
	// page size, and read-only flag without being handed them again.
	cfg syncplugin.Config
}

// compile-time proof this plugin satisfies the port. Without it, a drift
// between the interface and this implementation would only surface at the
// registry call site.
var _ syncplugin.Plugin = (*{{.TypeName}})(nil)

// New creates an unconnected plugin.
func New() *{{.TypeName}} {
	return &{{.TypeName}}{}
}

// Connect authenticates against the upstream system described by cfg.
func (p *{{.TypeName}}) Connect(_ context.Context, cfg syncplugin.Config) error {
	if err := cfg.Validate(); err != nil {
		return err
	}
	p.cfg = cfg
	// TODO(forge): resolve cfg.CredentialName through internal/credential
	// and authenticate. Returning an error keeps this honest until then.
	return errNotImplemented
}

// Discover streams raw upstream device data as Records.
func (p *{{.TypeName}}) Discover(_ context.Context) (syncplugin.RecordIterator, error) {
	// TODO(forge): page the upstream API and yield one Record per device.
	return nil, errNotImplemented
}

// Classify maps one discovered Record onto a device type and capability set.
func (p *{{.TypeName}}) Classify(_ context.Context, _ record.Record) (syncplugin.Classification, error) {
	// TODO(forge): derive a Section 6d classification path from the raw
	// record and resolve it with syncplugin.ClassifyPath. Until then this
	// quarantines every device, which is the visible, reviewable failure
	// Section 6g asks for rather than a silent misclassification.
	return syncplugin.Quarantine("sync plugin " + Name + " is declared but not implemented"), nil
}

// Sync reconciles every discovered device into repo.
func (p *{{.TypeName}}) Sync(_ context.Context, _ inv.Repository) (syncplugin.Reconciliation, error) {
	// TODO(forge): delegate to syncplugin.Reconcile once Discover and
	// Classify are real.
	return syncplugin.Reconciliation{}, errNotImplemented
}

// Close releases whatever Connect acquired.
//
// Unlike the four methods above, this returns nil rather than
// errNotImplemented: a skeleton has acquired nothing, so refusing to
// release it would be a lie in the other direction, and every caller
// closing in a defer would get a spurious error. Fill it in alongside
// Connect: whatever that opens, this closes.
func (p *{{.TypeName}}) Close() error {
	return nil
}
`

// pluginTestTemplateSource is the starter test template. It asserts the two
// things that are true of every generated plugin the moment it is
// generated: it is registered, and it refuses to pretend.
const pluginTestTemplateSource = `package {{.PackageName}}_test

import (
	"context"
	"testing"

	"github.com/Subject-Void-LLC/the-pleiades/internal/inventory/plugins/{{.PackageName}}"
	"github.com/Subject-Void-LLC/the-pleiades/internal/inventory/record"
	"github.com/Subject-Void-LLC/the-pleiades/internal/inventory/syncplugin"
)

// Test{{.TypeName}}_Registered proves the plugin is reachable through the
// shared registry. It does not prove the real binary can reach it: that
// needs a blank import in internal/inventory/plugins/builtins.go, which
// internal/archtest is what actually checks.
func Test{{.TypeName}}_Registered(t *testing.T) {
	desc, ok := syncplugin.Lookup({{.PackageName}}.Name)
	if !ok {
		t.Fatalf("plugin %q is not registered", {{.PackageName}}.Name)
	}
	if desc.New == nil {
		t.Fatal("registered descriptor has no constructor")
	}
	if desc.New() == nil {
		t.Fatal("constructor returned nil")
	}
	if desc.Description == "" {
		t.Error("registered descriptor has no description")
	}
}

// Test{{.TypeName}}_NotImplemented proves every method refuses out loud
// while this plugin is still declared. Delete the cases as you implement
// them; a case that starts failing is telling you a method became real, not
// that the test is wrong.
func Test{{.TypeName}}_NotImplemented(t *testing.T) {
	desc, ok := syncplugin.Lookup({{.PackageName}}.Name)
	if !ok {
		t.Fatalf("plugin %q is not registered", {{.PackageName}}.Name)
	}
	if desc.Implemented() {
		t.Skip("plugin reports StatusImplemented; these declared-stage assertions no longer apply")
	}

	ctx := context.Background()

	tests := []struct {
		name string
		call func(p syncplugin.Plugin) error
	}{
		{
			name: "Connect",
			call: func(p syncplugin.Plugin) error {
				return p.Connect(ctx, syncplugin.Config{Name: {{.PackageName}}.Name})
			},
		},
		{
			name: "Discover",
			call: func(p syncplugin.Plugin) error {
				_, err := p.Discover(ctx)
				return err
			},
		},
		{
			name: "Sync",
			call: func(p syncplugin.Plugin) error {
				_, err := p.Sync(ctx, nil)
				return err
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if err := tt.call(desc.New()); err == nil {
				t.Fatalf("%s returned nil; a declared plugin must refuse, never succeed", tt.name)
			}
		})
	}
}

// Test{{.TypeName}}_ClassifyQuarantines proves Classify is the one method
// that must not return an error even while unimplemented. Section 6g
// requires an unplaceable device to stay visible for manual review, and
// syncplugin.Reconcile stops the whole sync on a Classify error.
func Test{{.TypeName}}_ClassifyQuarantines(t *testing.T) {
	desc, ok := syncplugin.Lookup({{.PackageName}}.Name)
	if !ok {
		t.Fatalf("plugin %q is not registered", {{.PackageName}}.Name)
	}
	if desc.Implemented() {
		t.Skip("plugin reports StatusImplemented; these declared-stage assertions no longer apply")
	}

	cls, err := desc.New().Classify(context.Background(), record.Record{Name: "any-device"})
	if err != nil {
		t.Fatalf("Classify must not error while declared, got %v", err)
	}
	if !cls.Quarantined() {
		t.Error("a declared plugin must quarantine every device rather than guess a type")
	}
	if cls.Reason == "" {
		t.Error("a quarantined classification must explain why")
	}
}
`
