package filterscaffold

// implFuncTemplateSource is one generated pkg/filters function: a doc
// comment built from Config.Summary (and the malformed-vs-missing
// reminder every filter in this package carries, per pkg/filters'
// own package doc comment), and a body that panics rather than
// returning a plausible zero value.
//
// Panicking, not silently returning "" or 0, is the deliberate choice
// here: pkg/filters functions return a bare value, not a value plus an
// error (SafeInt returns int, not (int, error)), so there is no
// "declared but not implemented" error return the way
// collectionscaffold's stub uses. A caller of an unfinished filter
// finding out immediately and loudly, in a panic naming the function, is
// closer to that guardrail's spirit than a stub that returns 0 or ""
// and lets a caller mistake "not implemented" for "the answer is zero."
const implFuncTemplateSource = `package filters

// {{.GoName}} {{.Summary}}
//
// Generated by pleiades forge new-filter (internal/forge/filterscaffold).
// Category: {{.Category}}. Registered in CEL as filters.{{.CELName}}; see
// internal/engine/cel_filters.go for the binding
// (filterscaffold.Reminder prints the paste-ready block).
//
// TODO: implement. This stub panics rather than returning a plausible
// zero value, so a caller finds out immediately rather than mistaking
// "not implemented" for a real answer.
func {{.GoName}}({{.ParamList}}) {{.ReturnType}} {
	panic("filters.{{.CELName}}: not implemented")
}
`

// testFuncTemplateSource is the starter test for a generated filter
// function: honestly skipped, not asserting against a stub that would
// only panic if called, mirroring the same "a green test over an
// unfinished implementation is worse than an honest skip" discipline
// collectionscaffold's own generated
// Test<Function>_NotImplemented establishes for a different shape of
// stub.
const testFuncTemplateSource = `package filters_test

import "testing"

// Test{{.GoName}} is a placeholder. Replace with a real table-driven
// test (valid input, malformed input, whitespace/empty/over-cap edges,
// and a Fuzz target if this function parses a flat string) once
// filters.{{.GoName}} is implemented; see pkg/filters/cast_test.go and
// pkg/filters/cast_fuzz_test.go for the shape this package's own tests
// already established.
func Test{{.GoName}}(t *testing.T) {
	t.Skip("TODO: implement filters.{{.CELName}} (pkg/filters.{{.GoName}}) and this test")
}
`
