package tlscert

import (
	"crypto/tls"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// FuzzLoadNeverServesMaterialItCannotVerify is the file-content half of the
// TLS fuzzing this phase owes.
//
// The resolver fuzz in cmd/controller covers the environment strings that
// decide WHETHER to serve TLS. This covers the bytes that decide WHAT is
// served, which is the other input the operator controls and the one that
// arrives from a file rather than from a variable: a Kubernetes Secret, a
// bind mount, a copy that was truncated, a certificate pasted next to
// somebody else's key.
//
// THE PROPERTY. Load must either fail, or return a ServingCert that
// crypto/tls can genuinely present. There is no third outcome, and in
// particular there is no outcome where Load succeeds and the listener then
// fails at the first handshake, because that failure surfaces as "the site
// does not work" long after the process reported a clean start. So on every
// success this asserts what a handshake would need: a parsed leaf, a
// non-empty DER chain, a private key, and a leaf whose public key really is
// the one that key belongs to.
//
// That last check is the one worth having. tls.X509KeyPair is what catches
// a certificate sitting beside a key that does not belong to it, and this
// target exists partly to keep that guarantee from being lost if the
// parsing path is ever rearranged for a reason unrelated to it.
//
// Panics count as failures for free: the fuzzer treats them as crashes,
// which covers the empty-file, truncated-DER and enormous-input cases the
// phase's item names without needing a separate assertion for each.
func FuzzLoadNeverServesMaterialItCannotVerify(f *testing.F) {
	// A real, valid pair as the primary seed, so the corpus starts from
	// material that is supposed to load rather than only from garbage. It
	// is generated by this package's own generator, which is the same
	// material a self-provisioning controller writes.
	dir := f.TempDir()
	real, err := Generate(dir, Options{ExtraNames: []string{"fuzz.example"}})
	if err != nil {
		f.Fatalf("generating the seed certificate: %v", err)
	}
	certPEM, err := os.ReadFile(real.CertFile)
	if err != nil {
		f.Fatalf("reading the seed certificate: %v", err)
	}
	// KeyFile is the serving bundle: this package publishes the certificate
	// and its key as ONE file so the pair is replaced in a single rename.
	// CertFile above may be the key-free anchor copy beside it.
	servingPEM, err := os.ReadFile(real.KeyFile)
	if err != nil {
		f.Fatalf("reading the seed bundle: %v", err)
	}

	f.Add(servingPEM, servingPEM)                     // the bundle, which holds both halves
	f.Add(certPEM, servingPEM)                        // a certificate beside a bundle
	f.Add(certPEM, certPEM)                           // a certificate with no key at all
	f.Add([]byte{}, []byte{})                         // two empty files
	f.Add(servingPEM[:len(servingPEM)/2], servingPEM) // truncated mid-PEM
	f.Add([]byte("-----BEGIN CERTIFICATE-----\nnot base64\n-----END CERTIFICATE-----\n"), servingPEM)
	f.Add([]byte("-----BEGIN CERTIFICATE-----\n-----END CERTIFICATE-----\n"), servingPEM) // an empty block
	f.Add([]byte(strings.Repeat("A", 1<<16)), servingPEM)                                 // a large non-PEM file
	f.Add([]byte("\x00\x00\x00\x00"), []byte("\x00\x00\x00\x00"))                         // binary noise

	f.Fuzz(func(t *testing.T, certBytes, keyBytes []byte) {
		dir := t.TempDir()
		certPath := filepath.Join(dir, "cert.pem")
		keyPath := filepath.Join(dir, "key.pem")
		if err := os.WriteFile(certPath, certBytes, 0o600); err != nil {
			t.Skipf("could not stage the certificate file: %v", err)
		}
		if err := os.WriteFile(keyPath, keyBytes, 0o600); err != nil {
			t.Skipf("could not stage the key file: %v", err)
		}

		serving, err := Load(certPath, keyPath)
		if err != nil {
			// Refusing is always safe: the caller fails closed and the
			// process does not open a listener it cannot serve from.
			return
		}

		// Load said yes. Everything a handshake needs must now be present.
		if serving.Leaf == nil {
			t.Fatal("Load succeeded with no parsed leaf certificate; every caller reads Leaf")
		}
		if len(serving.Pair.Certificate) == 0 {
			t.Fatal("Load succeeded with an empty certificate chain, which crypto/tls cannot present")
		}
		if serving.Pair.PrivateKey == nil {
			t.Fatal("Load succeeded with no private key, so the first handshake would fail on a server that reported a clean start")
		}
		if serving.Roots == nil {
			t.Fatal("Load succeeded with no root pool; the container healthcheck verifies the listener against exactly this pool")
		}

		// And the pair really is a pair. This is the check that catches a
		// certificate stored beside a key that does not belong to it, which
		// is a state the two-file layout can genuinely produce.
		if _, err := tls.X509KeyPair(pemFor(t, certPath), pemFor(t, keyPath)); err != nil {
			t.Fatalf("Load accepted material that tls.X509KeyPair rejects: %v", err)
		}
	})
}

// pemFor re-reads a staged file, so the assertion above is made against the
// bytes on disk rather than against whatever the fuzzer handed in.
func pemFor(t *testing.T, path string) []byte {
	t.Helper()
	body, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("re-reading %s: %v", path, err)
	}
	return body
}
