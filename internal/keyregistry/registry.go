// Package keyregistry records which master encryption keys a database has
// been told about, by fingerprint, and never by value.
//
// It exists to answer "when did this key come into existence" for a
// database, which nothing could answer before: MASTER_ENCRYPTION_KEY lives
// in a deployment's environment, and the database it protects kept no record
// of which key that was or since when. It is also what gives the activity
// stream an object to point at when a key is generated, since an activity
// entry names a row, and a key had none.
//
// Two things write here. The setup command records a key it generated when
// it can reach the database. The controller records a current key it has
// never seen, at startup, which is how a key generated where no database
// was reachable (a Helm install makes its Secret before the database
// exists) still gets an entry, marked as first used rather than generated.
package keyregistry

import (
	"context"
	"errors"
	"fmt"
	"time"

	"github.com/Subject-Void-LLC/the-pleiades/internal/ent"
	"github.com/Subject-Void-LLC/the-pleiades/internal/ent/encryptionkey"
)

// Origin says which writer recorded a key.
type Origin string

// The two writers.
const (
	// OriginSetup is a key the setup command generated.
	OriginSetup Origin = "setup"

	// OriginFirstUse is a key a controller started with before any row
	// here named it.
	OriginFirstUse Origin = "first_use"
)

// Possession says whether the operator showed they held the key at the
// moment it was generated.
type Possession string

// The three answers, each of which is the honest one for some writer.
const (
	// PossessionChecked means the operator re-entered the whole key after
	// it was shown and removed from the screen.
	PossessionChecked Possession = "checked"

	// PossessionNotChecked means setup generated the key without a
	// terminal, so it was never shown and nobody re-entered it.
	PossessionNotChecked Possession = "not_checked"

	// PossessionNotApplicable means the key was generated somewhere this
	// database could not see, and first recorded when a controller used it.
	PossessionNotApplicable Possession = "not_applicable"
)

// Record is one registered key.
type Record struct {
	// ID is the row id, which is what an activity entry points at.
	ID int

	// Fingerprint is internal/crypto.Fingerprint of the key.
	Fingerprint string

	// Version is the version tag the key carried when it was recorded.
	Version string

	// Origin is which writer recorded it.
	Origin Origin

	// Possession is whether the operator took possession of it.
	Possession Possession

	// CreatedAt is when it was recorded.
	CreatedAt time.Time
}

// Describe names the record for a line a person reads: the short
// fingerprint, then how it came to be recorded. It is the object name an
// activity entry carries.
func (r Record) Describe() string {
	switch {
	case r.Origin == OriginFirstUse:
		return Short(r.Fingerprint) + " (first used by this database)"
	case r.Possession == PossessionChecked:
		return Short(r.Fingerprint) + " (generated by setup, possession checked)"
	default:
		return Short(r.Fingerprint) + " (generated by setup, possession not checked)"
	}
}

// Short renders the first eight hex characters of a fingerprint as two
// groups of four, "3f9a-c21b": short enough to read aloud and to type, and
// distinct enough that two keys a person is comparing will not share it.
// A fingerprint shorter than eight characters is returned as it is.
func Short(fingerprint string) string {
	if len(fingerprint) < 8 {
		return fingerprint
	}
	return fingerprint[:4] + "-" + fingerprint[4:8]
}

// ErrNotRegistered is returned by Get for a fingerprint no row names.
var ErrNotRegistered = errors.New("keyregistry: no key with that fingerprint is registered")

// Store reads and writes the registry.
type Store interface {
	// Register records r unless a row already names its fingerprint. It
	// returns the stored record, which is the existing one when there was
	// one, and whether this call created it. Registering the same key
	// twice is not an error, which is what lets several controller
	// replicas starting together each try.
	Register(ctx context.Context, r Record) (Record, bool, error)

	// Get returns the record naming fingerprint, or ErrNotRegistered.
	Get(ctx context.Context, fingerprint string) (Record, error)
}

// entStore is the Store backed by the encryption_keys table.
type entStore struct {
	client *ent.Client
}

// NewEntStore returns the Store backed by client.
func NewEntStore(client *ent.Client) Store {
	return &entStore{client: client}
}

// Register implements Store.
func (s *entStore) Register(ctx context.Context, r Record) (Record, bool, error) {
	if r.Fingerprint == "" || r.Version == "" {
		return Record{}, false, fmt.Errorf("keyregistry: a record needs a fingerprint and a version")
	}
	row, err := s.client.EncryptionKey.Create().
		SetFingerprint(r.Fingerprint).
		SetVersion(r.Version).
		SetOrigin(encryptionkey.Origin(r.Origin)).
		SetPossession(encryptionkey.Possession(r.Possession)).
		Save(ctx)
	if err == nil {
		return fromRow(row), true, nil
	}
	if !ent.IsConstraintError(err) {
		return Record{}, false, fmt.Errorf("keyregistry: recording key %s: %w", Short(r.Fingerprint), err)
	}
	// Another writer recorded the same key first. Theirs is the record.
	existing, getErr := s.Get(ctx, r.Fingerprint)
	if getErr != nil {
		return Record{}, false, fmt.Errorf("keyregistry: key %s was recorded concurrently and could not be read back: %w", Short(r.Fingerprint), getErr)
	}
	return existing, false, nil
}

// Get implements Store.
func (s *entStore) Get(ctx context.Context, fingerprint string) (Record, error) {
	row, err := s.client.EncryptionKey.Query().
		Where(encryptionkey.FingerprintEQ(fingerprint)).
		Only(ctx)
	if ent.IsNotFound(err) {
		return Record{}, ErrNotRegistered
	}
	if err != nil {
		return Record{}, fmt.Errorf("keyregistry: reading key %s: %w", Short(fingerprint), err)
	}
	return fromRow(row), nil
}

// fromRow converts a stored row to a Record.
func fromRow(row *ent.EncryptionKey) Record {
	return Record{
		ID:          row.ID,
		Fingerprint: row.Fingerprint,
		Version:     row.Version,
		Origin:      Origin(row.Origin),
		Possession:  Possession(row.Possession),
		CreatedAt:   row.CreatedAt,
	}
}
